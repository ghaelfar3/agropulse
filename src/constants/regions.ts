/**
 * Значение уже сохранено (например, свободным текстом до перехода на select)
 * и не совпадает ни с одним пунктом списка — используется, чтобы не
 * подставлять в `RegionSelect` то, чего в нём нет.
 */
export function isKnownRegion(value: string | null | undefined): value is RfRegion {
  return typeof value === 'string' && (RF_REGIONS as readonly string[]).includes(value);
}
